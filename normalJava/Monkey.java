public class Monkey {
    private String email;
    private int phone;
    public Monkey(String email, int phone) {
        this.email = email;
        this.phone = phone;
    }

    public String getEmail() {
        return email;
    }
    public int getPhone() {
        return phone;
    }
    public void setEmail(String email) {
        this.email = email;
    }
}
    

